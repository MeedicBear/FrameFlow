import asyncio
import os
import shutil
import sys
import uuid
from pathlib import Path
from typing import List, Optional

from fastapi import FastAPI, File, HTTPException, UploadFile, BackgroundTasks
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, StreamingResponse
from pydantic import BaseModel

from models import ExtractionRequest, FrameInfo, TaskProgress, VideoMetadata
from services.ffmpeg_service import (
    UPLOADS_DIR,
    TASKS_DIR,
    create_zip_archive,
    probe_video,
    run_extraction_process,
    tasks_db,
    tasks_frames,
    videos_metadata,
)

app = FastAPI(title="Video Frame Extractor API", version="1.0.0")

# Enable CORS for frontend development
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


class ExportZipRequest(BaseModel):
    frame_filenames: Optional[List[str]] = None


@app.get("/api/health")
async def health_check():
    return {"status": "healthy", "service": "video-frame-extractor"}


@app.post("/api/upload", response_model=VideoMetadata)
async def upload_video(file: UploadFile = File(...)):
    """Uploads a video file and returns probed metadata."""
    if not file.filename:
        raise HTTPException(status_code=400, detail="Filename missing")

    video_id = str(uuid.uuid4())[:8]
    ext = Path(file.filename).suffix or ".mp4"
    dest_filename = f"{video_id}{ext}"
    dest_path = UPLOADS_DIR / dest_filename

    try:
        with open(dest_path, "wb") as buffer:
            shutil.copyfileobj(file.file, buffer)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to save upload: {e}")

    try:
        metadata = await probe_video(dest_path, video_id, file.filename)
        return metadata
    except Exception as e:
        if dest_path.exists():
            dest_path.unlink()
        raise HTTPException(status_code=400, detail=f"Failed to probe video: {e}")


@app.get("/api/videos/{video_id}/stream")
async def stream_video(video_id: str):
    """Streams the uploaded video file with HTTP Range support for scrubbing."""
    # Find the video file by prefix
    matching = list(UPLOADS_DIR.glob(f"{video_id}.*"))
    if not matching:
        raise HTTPException(status_code=404, detail="Video not found")

    video_path = matching[0]
    return FileResponse(
        video_path,
        media_type="video/mp4",
        filename=video_path.name
    )


@app.post("/api/extract")
async def start_extraction(req: ExtractionRequest, background_tasks: BackgroundTasks):
    """Initiates an asynchronous frame extraction job."""
    matching = list(UPLOADS_DIR.glob(f"{req.video_id}.*"))
    if not matching:
        raise HTTPException(status_code=404, detail="Video not found")

    video_path = matching[0]
    metadata = videos_metadata.get(req.video_id)
    if not metadata:
        metadata = await probe_video(video_path, req.video_id, video_path.name)

    task_id = str(uuid.uuid4())[:8]

    # Initialize task status
    tasks_db[task_id] = TaskProgress(
        task_id=task_id,
        status="pending",
        progress_percent=0.0,
        frames_extracted=0,
        current_timestamp=0.0,
        total_expected_frames=None
    )

    # Launch extraction in background
    background_tasks.add_task(
        run_extraction_process,
        task_id=task_id,
        video_path=video_path,
        req=req,
        metadata=metadata
    )

    return {"task_id": task_id, "status": "pending"}


@app.get("/api/tasks/{task_id}/progress", response_model=TaskProgress)
async def get_progress(task_id: str):
    """Retrieves current extraction status and progress."""
    if task_id not in tasks_db:
        raise HTTPException(status_code=404, detail="Task not found")
    return tasks_db[task_id]


@app.get("/api/tasks/{task_id}/events")
async def stream_task_events(task_id: str):
    """Server-Sent Events (SSE) stream for real-time progress updates."""
    if task_id not in tasks_db:
        raise HTTPException(status_code=404, detail="Task not found")

    async def event_generator():
        while True:
            progress = tasks_db.get(task_id)
            if not progress:
                break

            data = progress.model_dump_json()
            yield f"data: {data}\n\n"

            if progress.status in ["completed", "failed"]:
                break
            await asyncio.sleep(0.3)

    return StreamingResponse(event_generator(), media_type="text/event-stream")


@app.get("/api/tasks/{task_id}/frames", response_model=List[FrameInfo])
async def get_frames(task_id: str):
    """Returns the list of frames generated by the extraction task."""
    if task_id not in tasks_db:
        raise HTTPException(status_code=404, detail="Task not found")
    return tasks_frames.get(task_id, [])


@app.get("/api/tasks/{task_id}/frames/{filename}")
async def serve_frame_image(task_id: str, filename: str):
    """Serves individual frame image."""
    frame_path = TASKS_DIR / task_id / "frames" / filename
    if not frame_path.exists():
        raise HTTPException(status_code=404, detail="Frame not found")

    media_type = "image/jpeg"
    if filename.endswith(".png"):
        media_type = "image/png"
    elif filename.endswith(".webp"):
        media_type = "image/webp"

    return FileResponse(frame_path, media_type=media_type)


@app.post("/api/tasks/{task_id}/export-zip")
async def export_zip(task_id: str, req: ExportZipRequest = ExportZipRequest()):
    """Builds a ZIP archive of frames and returns download metadata."""
    if task_id not in tasks_db:
        raise HTTPException(status_code=404, detail="Task not found")

    try:
        zip_path = create_zip_archive(task_id, req.frame_filenames)
        return {
            "zip_url": f"/api/tasks/{task_id}/download-zip",
            "file_size_bytes": zip_path.stat().st_size,
            "filename": zip_path.name
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to create ZIP: {e}")


@app.get("/api/tasks/{task_id}/download-zip")
async def download_zip(task_id: str):
    """Downloads the generated ZIP archive."""
    zip_path = TASKS_DIR / task_id / f"{task_id}_frames.zip"
    if not zip_path.exists():
        # Generate full zip if it doesn't already exist
        try:
            zip_path = create_zip_archive(task_id)
        except Exception:
            raise HTTPException(status_code=404, detail="ZIP archive not found")

    return FileResponse(
        zip_path,
        media_type="application/zip",
        filename=f"frames_{task_id}.zip"
    )

# Static file serving for built frontend if present
def get_frontend_dist() -> Path:
    if getattr(sys, "frozen", False):
        p = Path(getattr(sys, "_MEIPASS", "")) / "frontend" / "dist"
        if p.exists():
            return p
    return Path(__file__).resolve().parent.parent / "frontend" / "dist"

FRONTEND_DIST = get_frontend_dist()
if FRONTEND_DIST.exists():
    from fastapi.staticfiles import StaticFiles

    app.mount("/assets", StaticFiles(directory=FRONTEND_DIST / "assets"), name="assets")

    @app.get("/{full_path:path}")
    async def serve_frontend(full_path: str):
        # Don't intercept API routes
        if full_path.startswith("api/"):
            raise HTTPException(status_code=404, detail="API endpoint not found")
        file_path = FRONTEND_DIST / full_path
        if file_path.exists() and file_path.is_file():
            return FileResponse(file_path)
        return FileResponse(FRONTEND_DIST / "index.html")

